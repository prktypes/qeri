import type { Explanation } from '@qeri/shared';
import type { ReactNode } from 'react';
import { useState } from 'react';
import { ArrowLeft, Bookmark, BookmarkCheck, Lightbulb, Quote } from 'lucide-react';
import { saveToLibrary } from '../messaging';

/** Card framing + heading used by every explanation section (visual rhythm helper). */
function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="rounded-xl border border-neutral-200 bg-white p-4 shadow-sm dark:border-neutral-800 dark:bg-neutral-900">
      <h3 className="mb-2 flex items-center gap-2 text-xs font-semibold tracking-wide text-qeri-600 uppercase dark:text-qeri-400">
        {title}
      </h3>
      {children}
    </section>
  );
}

/**
 * The provenance badge is the panel's single honest engine signal (this explanation's
 * meta alone decides live vs demo); Save lives next to it as the one persistent-data
 * affordance on the card (plan.md §Phase 4).
 */
function MetaBadge({
  generator,
  model,
}: {
  generator: 'mock' | 'openrouter';
  model: string | null | undefined;
}) {
  if (generator === 'openrouter') {
    const short = model?.split('/').pop() ?? 'live AI';
    return (
      <span
        title={model ? `Generated by ${model} via OpenRouter` : 'Generated via OpenRouter'}
        className="ml-auto shrink-0 rounded-full bg-emerald-100 px-2 py-0.5 text-[10px] font-medium text-emerald-700 dark:bg-emerald-700/30 dark:text-emerald-200"
      >
        live AI · {short}
      </span>
    );
  }
  return (
    <span className="ml-auto shrink-0 rounded-full bg-qeri-100 px-2 py-0.5 text-[10px] font-medium text-qeri-700 dark:bg-qeri-700/30 dark:text-qeri-200">
      demo mode
    </span>
  );
}

type SaveUiState = 'idle' | 'saving' | 'failed';

function SaveButton({ explanation, saved }: { explanation: Explanation; saved: boolean }) {
  const [ui, setUi] = useState<SaveUiState>('idle');

  async function onSave(): Promise<void> {
    if (saved || ui === 'saving') return;
    setUi('saving');
    const ack = await saveToLibrary(explanation);
    // Library re-renders from storage regardless; locally we only surface failures.
    setUi(ack.ok ? 'idle' : 'failed');
    if (!ack.ok) window.setTimeout(() => setUi('idle'), 2200);
  }

  if (saved) {
    return (
      <span
        title="This explanation is in your library"
        className="flex shrink-0 items-center gap-1 rounded-full bg-qeri-100 px-2 py-0.5 text-[10px] font-semibold text-qeri-700 dark:bg-qeri-700/40 dark:text-qeri-200"
      >
        <BookmarkCheck className="h-3 w-3" aria-hidden="true" />
        saved
      </span>
    );
  }

  const label = ui === 'failed' ? 'Retry' : 'Save';
  return (
    <button
      type="button"
      title="Save this explanation to your library"
      aria-label="Save this explanation to your library"
      onClick={() => void onSave()}
      disabled={ui === 'saving'}
      className={`flex shrink-0 items-center gap-1 rounded-full px-2 py-0.5 text-[10px] font-semibold transition-colors ${
        ui === 'failed'
          ? 'bg-rose-100 text-rose-700 dark:bg-rose-700/30 dark:text-rose-200'
          : 'bg-neutral-100 text-neutral-600 hover:bg-qeri-100 hover:text-qeri-700 dark:bg-neutral-800 dark:text-neutral-300 dark:hover:bg-qeri-700/30 dark:hover:text-qeri-200'
      }`}
    >
      <Bookmark className="h-3 w-3" aria-hidden="true" />
      {label}
    </button>
  );
}

export function ExplanationView({
  explanation,
  saved,
  onBack,
}: {
  explanation: Explanation;
  saved: boolean;
  onBack?: () => void;
}) {
  const { request, summary, whyItMatters, keyTerms, example, caveats, followUps, meta } =
    explanation;

  return (
    <div className="flex min-h-full flex-col gap-3">
      {/* Back navigation when the card renders from the library (Phase 4) */}
      {onBack && (
        <button
          type="button"
          onClick={onBack}
          className="flex w-fit items-center gap-1.5 text-xs font-semibold text-neutral-500 transition-colors hover:text-qeri-600 dark:text-neutral-400 dark:hover:text-qeri-300"
        >
          <ArrowLeft className="h-3.5 w-3.5" aria-hidden="true" />
          Library
        </button>
      )}

      {/* Source post preview — a quote card first, so context precedes analysis */}
      <div className="rounded-xl border border-neutral-200 bg-white p-4 shadow-sm dark:border-neutral-800 dark:bg-neutral-900">
        <div className="mb-2 flex items-center gap-2 text-xs text-neutral-500">
          <Quote className="h-3.5 w-3.5 shrink-0" />
          <span className="truncate">
            {request.authorHandle ? `${request.authorHandle} · ` : ''}original post
          </span>
          <MetaBadge generator={meta.generator} model={meta.model} />
          <SaveButton explanation={explanation} saved={saved} />
        </div>
        <p className="line-clamp-6 text-sm whitespace-pre-line text-neutral-700 dark:text-neutral-300">
          {request.text}
        </p>
      </div>

      {/* Thread context (Phase 2): quoted-post or parent-post snippet, labeled by kind */}
      {request.context && (
        <Section
          title={
            request.contextKind === 'quoted'
              ? 'Quotes this post'
              : request.contextKind === 'parent'
                ? 'Replying to'
                : 'Thread context'
          }
        >
          <p className="line-clamp-4 text-sm leading-relaxed whitespace-pre-line text-neutral-600 dark:text-neutral-400">
            {request.context}
          </p>
        </Section>
      )}

      <Section title="In simple terms">
        <p className="text-sm leading-relaxed text-neutral-800 dark:text-neutral-200">
          {summary}
        </p>
      </Section>

      <Section title="Why it matters">
        <p className="text-sm leading-relaxed text-neutral-800 dark:text-neutral-200">
          {whyItMatters}
        </p>
      </Section>

      {keyTerms.length > 0 && (
        <Section title="Key terms">
          <dl className="flex flex-col gap-2">
            {keyTerms.map((entry) => (
              <div key={entry.term} className="text-sm">
                <dt className="font-semibold text-neutral-900 dark:text-neutral-100">
                  {entry.term}
                </dt>
                <dd className="text-neutral-600 dark:text-neutral-400">{entry.definition}</dd>
              </div>
            ))}
          </dl>
        </Section>
      )}

      <Section title="Example">
        <p className="text-sm leading-relaxed text-neutral-800 dark:text-neutral-200">
          {example}
        </p>
      </Section>

      {caveats.length > 0 && (
        <Section title="Caveats">
          <ul className="flex list-disc flex-col gap-1 pl-4 text-sm text-neutral-600 dark:text-neutral-400">
            {caveats.map((caveat) => (
              <li key={caveat}>{caveat}</li>
            ))}
          </ul>
        </Section>
      )}

      {followUps.length > 0 && (
        <Section title="Follow-ups">
          <div className="flex flex-wrap gap-2">
            {followUps.map((prompt) => (
              <span
                key={prompt}
                className="rounded-full border border-qeri-200 bg-qeri-50 px-3 py-1.5 text-xs font-medium text-qeri-700 opacity-70 dark:border-qeri-700/50 dark:bg-qeri-700/20 dark:text-qeri-200"
                title="Interactive follow-ups arrive with the AI integration in Phase 3"
              >
                <Lightbulb className="mr-1 inline h-3 w-3" />
                {prompt}
              </span>
            ))}
          </div>
        </Section>
      )}

      <footer className="mt-auto pt-2 text-center text-[11px] text-neutral-400">
        {meta.generator === 'mock' ? 'Demo content · ' : ''}
        {meta.generationMs} ms · schema v{meta.schemaVersion}
      </footer>
    </div>
  );
}
