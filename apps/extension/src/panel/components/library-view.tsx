import { useEffect, useRef, useState } from 'react';
import { Library, Trash2 } from 'lucide-react';
import { type SavedExplanation, type SavedLibrary } from '@qeri/shared';
import { clearLibraryViaWorker, deleteFromLibrary } from '../messaging';

const DATE_FORMAT = new Intl.DateTimeFormat(undefined, {
  month: 'short',
  day: 'numeric',
  hour: '2-digit',
  minute: '2-digit',
});

function EntryCard({
  entry,
  onOpen,
}: {
  entry: SavedExplanation;
  onOpen: (entry: SavedExplanation) => void;
}) {
  const [deleting, setDeleting] = useState(false);
  const { explanation, savedAt } = entry;
  const isLive = explanation.meta.generator === 'openrouter';

  async function onDelete(): Promise<void> {
    if (deleting) return;
    setDeleting(true);
    // Ack decides nothing visual — storage.onChanged removes the row either way.
    await deleteFromLibrary(explanation.id);
  }

  return (
    <li className="rounded-xl border border-neutral-200 bg-white p-3 shadow-sm transition-colors hover:border-qeri-300 dark:border-neutral-800 dark:bg-neutral-900 dark:hover:border-qeri-700">
      <button
        type="button"
        onClick={() => onOpen(entry)}
        className="w-full text-left"
        aria-label={`Open saved explanation of a post by ${explanation.request.authorHandle ?? 'unknown author'}`}
      >
        <div className="mb-1 flex items-center gap-2 text-[11px] text-neutral-500 dark:text-neutral-400">
          <span
            aria-hidden="true"
            className={`h-1.5 w-1.5 shrink-0 rounded-full ${isLive ? 'bg-emerald-500' : 'bg-qeri-400'}`}
            title={isLive ? 'Generated live by AI' : 'Generated by the demo fallback'}
          />
          <span className="truncate font-medium text-neutral-700 dark:text-neutral-300">
            {explanation.request.authorHandle ?? 'Unknown author'}
          </span>
          <span className="shrink-0 text-neutral-400">
            {DATE_FORMAT.format(new Date(savedAt))}
          </span>
        </div>
        <p className="line-clamp-2 text-sm text-neutral-600 dark:text-neutral-400">
          {explanation.request.text}
        </p>
      </button>
      <div className="mt-2 flex items-center justify-end gap-1">
        <button
          type="button"
          onClick={() => onOpen(entry)}
          className="rounded-md px-2 py-1 text-[11px] font-semibold text-qeri-600 transition-colors hover:bg-qeri-50 dark:text-qeri-300 dark:hover:bg-qeri-700/20"
        >
          Open
        </button>
        <button
          type="button"
          onClick={() => void onDelete()}
          disabled={deleting}
          aria-label="Delete this saved explanation"
          title="Delete"
          className="rounded-md p-1.5 text-neutral-400 transition-colors hover:bg-rose-50 hover:text-rose-600 disabled:opacity-40 dark:hover:bg-rose-700/20 dark:hover:text-rose-300"
        >
          <Trash2 className="h-3.5 w-3.5" aria-hidden="true" />
        </button>
      </div>
    </li>
  );
}

/**
 * The saved-knowledge library (plan.md §Phase 4 stage 1).
 *
 * Entries live in chrome.storage.local on this device — stated honestly in the
 * footer, because "where is my data" is the first privacy question users ask.
 * Clearing is a deliberate two-step confirm: one click arms, a second commits,
 * and the disarm timer keeps a stray first click from ever becoming a purge.
 */
export function LibraryView({
  library,
  onOpen,
}: {
  library: SavedLibrary;
  onOpen: (entry: SavedExplanation) => void;
}) {
  const entries = library.entries;
  const [clearArmed, setClearArmed] = useState(false);
  const disarmTimer = useRef<number | null>(null);

  useEffect(
    () => () => {
      if (disarmTimer.current !== null) window.clearTimeout(disarmTimer.current);
    },
    [],
  );

  function armClear(): void {
    setClearArmed(true);
    disarmTimer.current = window.setTimeout(() => setClearArmed(false), 3500);
  }

  async function commitClear(): Promise<void> {
    if (disarmTimer.current !== null) window.clearTimeout(disarmTimer.current);
    setClearArmed(false);
    await clearLibraryViaWorker();
  }

  if (entries.length === 0) {
    return (
      <div className="rounded-xl border border-dashed border-neutral-300 bg-white p-8 text-center dark:border-neutral-700 dark:bg-neutral-900">
        <Library
          className="mx-auto mb-3 h-8 w-8 text-neutral-300 dark:text-neutral-600"
          aria-hidden="true"
        />
        <h2 className="text-sm font-semibold text-neutral-700 dark:text-neutral-300">
          Nothing saved yet
        </h2>
        <p className="mt-1 text-xs text-neutral-500 dark:text-neutral-400">
          Explain a post and press <span className="font-semibold">Save</span> to keep it here —
          your library survives browser restarts.
        </p>
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-3">
      <div className="flex items-center justify-between rounded-xl border border-neutral-200 bg-white px-4 py-3 shadow-sm dark:border-neutral-800 dark:bg-neutral-900">
        <div>
          <h2 className="text-sm font-semibold text-neutral-800 dark:text-neutral-200">
            Saved knowledge
            <span className="ml-2 text-xs font-normal text-neutral-500">{entries.length}</span>
          </h2>
          <p className="text-[11px] text-neutral-500 dark:text-neutral-400">
            stored locally in this browser
          </p>
        </div>

        {clearArmed ? (
          <button
            type="button"
            onClick={() => void commitClear()}
            className="rounded-md bg-rose-600 px-2.5 py-1.5 text-[11px] font-semibold text-white transition-colors hover:bg-rose-700"
          >
            Clear everything?
          </button>
        ) : (
          <button
            type="button"
            onClick={armClear}
            className="rounded-md px-2.5 py-1.5 text-[11px] font-semibold text-neutral-500 transition-colors hover:bg-rose-50 hover:text-rose-600 dark:text-neutral-400 dark:hover:bg-rose-700/20 dark:hover:text-rose-300"
          >
            Clear all
          </button>
        )}
      </div>

      <ul className="flex flex-col gap-2">
        {entries.map((entry) => (
          <EntryCard key={entry.explanation.id} entry={entry} onOpen={onOpen} />
        ))}
      </ul>
    </div>
  );
}
